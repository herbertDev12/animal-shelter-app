-- ---------------------------------------------------------------------------

ALTER TABLE "Clinic" ADD CONSTRAINT "Clinic_pkey" PRIMARY KEY ("id_clinic");
ALTER TABLE "Supplier" ADD CONSTRAINT "Supplier_pkey" PRIMARY KEY ("id_supplier");
ALTER TABLE "Veterinarian" ADD CONSTRAINT "Veterinarian_pkey" PRIMARY KEY ("id_supplier");
ALTER TABLE "Contract" ADD CONSTRAINT "Contract_pkey" PRIMARY KEY ("id_contract");
ALTER TABLE "TransportService" ADD CONSTRAINT "TransportService_pkey" PRIMARY KEY ("id_contract");
ALTER TABLE "ServiceOffered" ADD CONSTRAINT "ServiceOffered_pkey" PRIMARY KEY ("id_service");
ALTER TABLE "Animal" ADD CONSTRAINT "Animal_pkey" PRIMARY KEY ("id_animal");
ALTER TABLE "Activity" ADD CONSTRAINT "Activity_pkey" PRIMARY KEY ("id_activity");
ALTER TABLE "Adoption" ADD CONSTRAINT "Adoption_pkey" PRIMARY KEY ("id_adoption");
