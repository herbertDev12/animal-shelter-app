ALTER TABLE "Veterinarian" ADD CONSTRAINT "Veterinarian_id_supplier_fkey" FOREIGN KEY ("id_supplier") REFERENCES "Supplier"("id_supplier") ON DELETE NO ACTION ON UPDATE NO ACTION;
