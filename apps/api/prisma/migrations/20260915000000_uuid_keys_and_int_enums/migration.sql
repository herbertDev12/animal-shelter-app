-- ---------------------------------------------------------------------------
-- 6. String enumerations -> SMALLINT (values mirror packages/schemas/src/enums.ts)
--
-- The old CHECK constraints guaranteed only these strings exist, so every row
-- maps. Defaults are dropped before the type change because 'Active' /
-- 'available' cannot be cast to SMALLINT. The indexes on these columns are
-- rebuilt automatically by ALTER COLUMN ... TYPE.
-- ---------------------------------------------------------------------------

ALTER TABLE "Supplier" DROP CONSTRAINT "Supplier_type_check";
ALTER TABLE "Contract" DROP CONSTRAINT "Contract_contract_category_check";
ALTER TABLE "Contract" DROP CONSTRAINT "Contract_status_check";
ALTER TABLE "Animal" DROP CONSTRAINT "Animal_status_check";

-- SupplierType: 1 Veterinarian, 2 Food Company, 3 Service Company
ALTER TABLE "Supplier" ALTER COLUMN "type" TYPE SMALLINT USING (
  CASE "type"
    WHEN 'Veterinarian' THEN 1
    WHEN 'Food Company' THEN 2
    WHEN 'Service Company' THEN 3
  END
);

-- ContractCategory: 1 Veterinarian, 2 Food, 3 Service
ALTER TABLE "Contract" ALTER COLUMN "contract_category" TYPE SMALLINT USING (
  CASE "contract_category"
    WHEN 'Veterinarian' THEN 1
    WHEN 'Food' THEN 2
    WHEN 'Service' THEN 3
  END
);

-- ContractStatus: 1 Active, 2 Inactive, 3 Expired
ALTER TABLE "Contract" ALTER COLUMN "status" DROP DEFAULT;
ALTER TABLE "Contract" ALTER COLUMN "status" TYPE SMALLINT USING (
  CASE "status"
    WHEN 'Active' THEN 1
    WHEN 'Inactive' THEN 2
    WHEN 'Expired' THEN 3
  END
);
ALTER TABLE "Contract" ALTER COLUMN "status" SET DEFAULT 1;

-- AnimalStatus: 1 Available, 2 Adopted, 3 Reserved, 4 Deceased
ALTER TABLE "Animal" ALTER COLUMN "status" DROP DEFAULT;
ALTER TABLE "Animal" ALTER COLUMN "status" TYPE SMALLINT USING (
  CASE "status"
    WHEN 'available' THEN 1
    WHEN 'adopted' THEN 2
    WHEN 'reserved' THEN 3
    WHEN 'deceased' THEN 4
  END
);
ALTER TABLE "Animal" ALTER COLUMN "status" SET DEFAULT 1;

ALTER TABLE "Supplier" ADD CONSTRAINT "Supplier_type_check"
  CHECK ("type" IN (1, 2, 3));

ALTER TABLE "Contract" ADD CONSTRAINT "Contract_contract_category_check"
  CHECK ("contract_category" IN (1, 2, 3));

ALTER TABLE "Contract" ADD CONSTRAINT "Contract_status_check"
  CHECK ("status" IN (1, 2, 3));

ALTER TABLE "Animal" ADD CONSTRAINT "Animal_status_check"
  CHECK ("status" IN (1, 2, 3, 4));
